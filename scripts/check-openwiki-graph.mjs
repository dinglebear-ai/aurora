import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { parse } from "yaml"

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.dirname(SCRIPT_DIR)
const LOCKFILE_PATH = path.join(REPO_ROOT, "pnpm-lock.yaml")
const MANIFEST_PATH = path.join(REPO_ROOT, "ops", "openwiki-graph.txt")

function dependencyReference(dependency) {
  if (typeof dependency === "string") return dependency
  if (dependency && typeof dependency === "object" && typeof dependency.version === "string") {
    return dependency.version
  }
  return undefined
}

export function packageVersion(reference) {
  if (typeof reference !== "string" || reference.length === 0) {
    throw new Error("Dependency reference must be a non-empty string")
  }
  const peerContext = reference.indexOf("(")
  return peerContext === -1 ? reference : reference.slice(0, peerContext)
}

export function snapshotKeyFor(name, reference, snapshots) {
  if (/^(?:file|link|workspace):/u.test(reference)) {
    throw new Error("OpenWiki graph contains unsupported local dependency " + name + "@" + reference)
  }
  if (reference.startsWith("npm:")) {
    throw new Error("OpenWiki graph contains unsupported npm alias " + name + "@" + reference)
  }

  const key = name + "@" + reference
  if (!Object.hasOwn(snapshots, key)) {
    throw new Error("OpenWiki graph references missing snapshot " + key)
  }
  return key
}

export function collectOpenWikiPackages(lockfile) {
  const importer = lockfile?.importers?.["."]
  const openwiki = importer?.devDependencies?.openwiki ?? importer?.dependencies?.openwiki
  const rootReference = dependencyReference(openwiki)
  if (!rootReference) {
    throw new Error("pnpm-lock.yaml does not expose OpenWiki in the root importer")
  }

  const snapshots = lockfile?.snapshots
  if (!snapshots || typeof snapshots !== "object") {
    throw new Error("pnpm-lock.yaml does not contain a snapshots map")
  }

  const packages = new Set()
  const visitedSnapshots = new Set()
  const stack = [{ name: "openwiki", reference: rootReference }]

  while (stack.length > 0) {
    const current = stack.pop()
    if (!current) continue

    const key = snapshotKeyFor(current.name, current.reference, snapshots)
    packages.add(current.name + "@" + packageVersion(current.reference))
    if (visitedSnapshots.has(key)) continue
    visitedSnapshots.add(key)

    const snapshot = snapshots[key]
    for (const field of ["dependencies", "optionalDependencies"]) {
      const dependencies = snapshot?.[field]
      if (!dependencies || typeof dependencies !== "object") continue

      for (const [name, dependency] of Object.entries(dependencies)) {
        const reference = dependencyReference(dependency)
        if (!reference) {
          throw new Error("OpenWiki snapshot " + key + " has an invalid reference for " + name)
        }
        stack.push({ name, reference })
      }
    }
  }

  return [...packages].sort((a, b) => a.localeCompare(b))
}

export function parseOpenWikiLockfile(source) {
  const lockfile = parse(source)
  if (!lockfile || typeof lockfile !== "object") {
    throw new Error("pnpm-lock.yaml did not parse to an object")
  }
  return lockfile
}

export function renderOpenWikiGraph(packages) {
  return [
    "# OpenWiki reachable dependency graph",
    "# Generated by: pnpm run openwiki:graph:update",
    "# Review every package addition, removal, and version change.",
    "",
    ...packages,
    "",
  ].join("\n")
}

export function parseManifestPackages(manifest) {
  return manifest
    .split(/\r?\n/u)
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith("#"))
}

export function diffOpenWikiGraph(expectedManifest, actualPackages) {
  const expected = new Set(parseManifestPackages(expectedManifest))
  const actual = new Set(actualPackages)
  return {
    added: [...actual].filter((entry) => !expected.has(entry)).sort(),
    removed: [...expected].filter((entry) => !actual.has(entry)).sort(),
  }
}

function printChanges({ added, removed }) {
  if (added.length > 0) {
    console.error("Added to the OpenWiki graph:")
    for (const entry of added) console.error("  + " + entry)
  }
  if (removed.length > 0) {
    console.error("Removed from the OpenWiki graph:")
    for (const entry of removed) console.error("  - " + entry)
  }
}

function main() {
  const lockfile = parseOpenWikiLockfile(readFileSync(LOCKFILE_PATH, "utf8"))
  const packages = collectOpenWikiPackages(lockfile)
  const rendered = renderOpenWikiGraph(packages)

  if (process.argv.includes("--write")) {
    writeFileSync(MANIFEST_PATH, rendered)
    console.log("Wrote " + packages.length + " OpenWiki graph entries to " + MANIFEST_PATH)
    return
  }

  if (!existsSync(MANIFEST_PATH)) {
    throw new Error("Missing OpenWiki graph manifest. Run: pnpm run openwiki:graph:update")
  }

  const expected = readFileSync(MANIFEST_PATH, "utf8")
  if (expected !== rendered) {
    printChanges(diffOpenWikiGraph(expected, packages))
    throw new Error("OpenWiki dependency graph changed. Review it, then run: pnpm run openwiki:graph:update")
  }

  const cloudCredentialPackages = packages.filter((entry) =>
    entry.startsWith("@aws-sdk/credential-provider-") || entry.startsWith("google-auth-library@")
  )
  console.log(
    "OpenWiki graph matches " + packages.length + " pinned packages; cloud credential packages: " +
      cloudCredentialPackages.length
  )
}

const entrypoint = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : ""
if (entrypoint === import.meta.url) main()
